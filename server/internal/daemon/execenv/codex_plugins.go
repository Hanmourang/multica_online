package execenv

import (
	"fmt"
	"log/slog"
	"os"
	"regexp"
	"strings"
)

// Background
//
// Codex 0.139+ enables the plugin marketplace by default. On startup,
// API-key / Bedrock / unauthenticated sessions sync the curated catalog
// from `https://github.com/openai/plugins.git` into `$CODEX_HOME/.tmp/
// plugins-clone-*` (openai/codex#25691, #27416, PR #29005). That fetch
// is synchronous with initialize / thread setup and has no useful
// timeout: on a host that cannot reach GitHub — typical behind the GFW
// or a locked-down corp network — the app-server sits silent for tens
// of minutes while Multica's UI shows only "thinking".
//
// ChatGPT-login sessions can skip the curated clone when remote plugins
// are available, but Multica's daemon-managed tasks commonly run with
// `auth_mode: apikey`, which still requires the local marketplace sync.
//
// Multica already has its own plugin/skill layer. Codex's marketplace
// is not how those skills are delivered, so turning the Codex-native
// feature off does not drop Multica plugins. The override only touches
// the per-task `CODEX_HOME/config.toml`; the user's global
// `~/.codex/config.toml` is never modified.
//
// Users who explicitly want Codex native plugins inside a Multica task
// (and accept the GitHub-sync stall) can keep the feature enabled by
// setting `MULTICA_CODEX_PLUGINS=1` in the daemon environment.
//
// Layout note
//
// Same TOML trap as the multi-agent / memory managed blocks: if the
// user's config already has a top-level `[features]` table, the
// override must be injected inside that table. Writing
// `features.plugins = false` at the root would redefine `features` and
// Codex's `toml-rs` would refuse to load the file.

// MulticaCodexPluginsEnv is the env var users can set to keep Codex
// native plugins enabled inside daemon-managed tasks. Anything truthy
// (1, true, yes, on; case-insensitive) keeps the feature on; everything
// else (including unset) disables it.
const MulticaCodexPluginsEnv = "MULTICA_CODEX_PLUGINS"

const (
	multicaPluginsBeginMarker = "# BEGIN multica-managed plugins (do not edit; regenerated by daemon)"
	multicaPluginsEndMarker   = "# END multica-managed plugins"
)

var pluginsBlockRe = regexp.MustCompile(
	`(?ms)^` + regexp.QuoteMeta(multicaPluginsBeginMarker) +
		`.*?^` + regexp.QuoteMeta(multicaPluginsEndMarker) + `\n*`)

var (
	featuresTablePluginsRe = regexp.MustCompile(`^\s*plugins\s*=`)
	rootDottedPluginsRe    = regexp.MustCompile(`^\s*features\s*\.\s*plugins\s*=`)
)

// codexPluginsEnabled reports whether the user opted into keeping Codex
// native plugins on for daemon-managed tasks.
func codexPluginsEnabled() bool {
	raw := strings.TrimSpace(os.Getenv(MulticaCodexPluginsEnv))
	switch strings.ToLower(raw) {
	case "1", "true", "yes", "on":
		return true
	}
	return false
}

func renderMulticaPluginsBlock(inFeaturesTable bool) string {
	var b strings.Builder
	b.WriteString(multicaPluginsBeginMarker)
	b.WriteString("\n")
	if inFeaturesTable {
		b.WriteString("plugins = false\n")
	} else {
		b.WriteString("features.plugins = false\n")
	}
	b.WriteString(multicaPluginsEndMarker)
	b.WriteString("\n")
	return b.String()
}

func stripUserPluginDirectives(content string) string {
	lines := strings.Split(content, "\n")
	out := make([]string, 0, len(lines))
	currentTable := ""
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if rootFeaturesTableHeaderRe.MatchString(line) {
			currentTable = "[features]"
			out = append(out, line)
			continue
		}
		if strings.HasPrefix(trimmed, "[") {
			currentTable = trimmed
			out = append(out, line)
			continue
		}
		switch currentTable {
		case "":
			if rootDottedPluginsRe.MatchString(trimmed) {
				continue
			}
		case "[features]":
			if featuresTablePluginsRe.MatchString(trimmed) {
				continue
			}
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

func injectPluginsBlockIntoFeaturesTable(content string) string {
	block := renderMulticaPluginsBlock(true)
	blockLines := strings.Split(strings.TrimRight(block, "\n"), "\n")
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		if !rootFeaturesTableHeaderRe.MatchString(line) {
			continue
		}
		out := make([]string, 0, len(lines)+len(blockLines))
		out = append(out, lines[:i+1]...)
		out = append(out, blockLines...)
		out = append(out, lines[i+1:]...)
		return strings.Join(out, "\n")
	}
	return content
}

// ensureCodexPluginsConfig writes the daemon-managed plugins block into
// the per-task config.toml so Codex skips the curated GitHub marketplace
// sync on startup. Idempotent: running it twice produces the same file.
//
// When MULTICA_CODEX_PLUGINS is set to a truthy value, the function is a
// no-op — the user has explicitly opted into Codex native plugins and
// accepts the startup-sync stall. The per-task config is recreated per
// task, so users should set the var once at daemon start.
func ensureCodexPluginsConfig(configPath string, logger *slog.Logger) error {
	if codexPluginsEnabled() {
		if logger != nil {
			logger.Info("codex plugins: leaving Codex native plugins untouched per MULTICA_CODEX_PLUGINS",
				"config_path", configPath,
			)
		}
		return nil
	}

	data, err := os.ReadFile(configPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read config.toml: %w", err)
	}
	existing := string(data)

	existing = pluginsBlockRe.ReplaceAllString(existing, "")
	existing = stripUserPluginDirectives(existing)

	var updated string
	if hasRootFeaturesTable(existing) {
		updated = injectPluginsBlockIntoFeaturesTable(existing)
	} else {
		existing = strings.TrimLeft(existing, "\n")
		block := renderMulticaPluginsBlock(false)
		if existing == "" {
			updated = block
		} else {
			updated = block + "\n" + existing
		}
	}

	if updated == string(data) {
		return nil
	}

	if err := os.WriteFile(configPath, []byte(updated), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}
